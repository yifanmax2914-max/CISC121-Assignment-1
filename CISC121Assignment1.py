#TapeEquilibrium
def solution(A):
  #test if empty
  if len(A) == 0:
    return 0
  #largest possible number
  smallest = sum(A)
  #loop to find out the smallest one
  for i in range(len(A)):
    if abs(sum(A) - 2 * sum(A[0:i+1])) < smallest:
      smallest = abs(sum(A) - 2 * sum(A[0:i+1]))

  return smallest

print(solution([3, 1, 8, 4, 3]))

#MissingInteger
def solution(A):
  #an empty array to store all integars
  integer = [0] * 1000000
  #put all integars in A to position
  for i in range(len(A)):
    if A[i] > 0:
      integer[A[i]] = A[i]
  #find out the first empty position
  for j in range(len(integer)):
    if integer[j] != j:
      return j

print(solution([1, 1, 5, 2, 4]))

#MaxCounters
def solution(N, A):
  max_value = 0
  B = [0] * N
  #execute increasing/max
  for i in range(len(A)):
    #increase
    if A[i] <= N:
      B[A[i] - 1] += 1
      #update max value
      if B[A[i] - 1] > max_value:
        max_value = B[A[i] - 1]

      continue
    #max
    else:
      for j in range(len(B)):
        B[j] = max_value

  return B

print(solution(5, [3, 5, 6, 4, 1, 6, 4]))

