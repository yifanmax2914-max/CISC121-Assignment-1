#CyclicRotation
def solution(A, K):
  #test if A is empty
  if len(A) == 0:
    return A
  else:
    result = [None] * len(A)
  #transfer the rotated array
  for i in range(len(A)):
    result[i] = A[(i - K) % len(A)]

  return result

print(solution([3, 4, 9, 7, 10], 3))

