def solution(A):
  if len(A) == 0:
    return 0

  smallest = sum(A)

  for i in range(len(A)):
    if abs(sum(A) - 2 * sum(A[0:i+1])) < smallest:
      smallest = abs(sum(A) - 2 * sum(A[0:i+1]))

  return smallest

