def solution(N, A):
  max_value = 0
  B = [0] * N

  for i in range(len(A)):
    if A[i] <= N:
      B[A[i] - 1] += 1

      if B[A[i] - 1] > max_value:
        max_value = B[A[i] - 1]

      continue

    else:
      for j in range(len(B)):
        B[j] = max_value

  return B

print(solution(5, [3, 5, 6, 4, 1, 6, 4]))

